import argparse
import sys
import json
import os
import matplotlib.pyplot as plt
import numpy as np
import re

# Threshold for outliers in milliseconds (500 ms)
OUTLIER_THRESHOLD_MS = 500

# Function to parse run number from filename or directory name
def parse_run_number(name):
    """
    Parses the run number from a filename or directory name.
    Expected formats:
      - ends with -N -> Run N (where N >= 2)
      - no -N suffix -> Run 1
    """
    # Remove extension if present
    if name.endswith(".json"):
        name = name[:-5]
        
    # Check for -N suffix
    parts = name.split('-')
    if len(parts) > 1 and parts[-1].isdigit():
        val_str = parts[-1]
        val = int(val_str)
        
        # Check for leading zeros: "02" -> not a run number generated by script
        # If valid run suffix (>=2 and no leading zero), return it
        if not (len(val_str) > 1 and val_str.startswith('0')) and val >= 2:
            return val
            
    return 1 # Default to run 1 if no run number is found

def parse_p99_value(p99_str):
    if isinstance(p99_str, (int, float)):
        return float(p99_str)
    p99_str = str(p99_str)
    if p99_str.endswith("ms"):
        return float(p99_str.replace("ms", ""))
    if p99_str.endswith("us"):
        return float(p99_str.replace("us", "")) / 1000.0
    if p99_str.endswith("s"):
        return float(p99_str.replace("s", "")) * 1000.0
    if p99_str.endswith("m"):
        return float(p99_str.replace("m", "")) * 60.0 * 1000.0
    return float(p99_str)

def get_latencies(data):
    latencies = []
    target_workload = "mixed-workload"
    workload_data = data.get(target_workload, [])
    if not workload_data:
        return []
        
    runs = workload_data if isinstance(workload_data, list) else [workload_data]
    for run in runs:
        p99_str = run.get("p99")
        if p99_str:
            try:
                val = parse_p99_value(p99_str)
                latencies.append(val)
            except ValueError:
                pass
    return latencies

def get_avg_p99_from_file(filepath):
    try:
        with open(filepath, 'r') as f:
            data = json.load(f)
        latencies = get_latencies(data)
        if latencies:
            return sum(latencies) / len(latencies)
    except Exception as e:
        # print(f"Warning: Error reading {filepath}: {e}")
        pass
    return None

if __name__ == "__main__":
    # Parse arguments and verify results directory
    parser = argparse.ArgumentParser(description='Visualize Kubernetes Experiment Results')
    parser.add_argument('results_dir', help='Directory containing result JSON files')
    parser.add_argument('--config', help='Specific configuration ID to display (e.g., P0, P1-2)')
    parser.add_argument('--aggregate-folders', action='store_true', help='Aggregate results from results-config-* folders')
    parser.add_argument('--run', type=int, help='Specific run number to process (1, 2, ...)')
    parser.add_argument('--differences', nargs=2, metavar=('V1', 'V2'), help='Calculate statistics on differences between two versions of configs')
    parser.add_argument('--exclude-outliers', action='store_true', help=f'Exclude configs with avg P99 latency above {OUTLIER_THRESHOLD_MS} ms in either version')
    args = parser.parse_args()
    results_dir = args.results_dir
    target_config = args.config
    aggregate_folders = args.aggregate_folders
    target_run = args.run
    exclude_threshold = OUTLIER_THRESHOLD_MS if args.exclude_outliers else None

    if not os.path.exists(results_dir):
        print(f"Error: Directory {results_dir} does not exist.")
        sys.exit(1)

    # Mode 3: Differences
    if args.differences:
        v1_suffix, v2_suffix = args.differences
        configs_v1 = {}
        configs_v2 = {}
        if not os.path.isdir(results_dir):
             print(f"Error: {results_dir} is not a directory.")
             sys.exit(1)
             
        files = [f for f in os.listdir(results_dir) if f.endswith(".json")]
        for filename in files:
            filepath = os.path.join(results_dir, filename)
            val = get_avg_p99_from_file(filepath)
            if val is None:
                continue
                
            # Match V1
            match_v1 = False
            prefix_v1 = None
            if filename.endswith(v1_suffix + ".json"):
                # Extract prefix
                suffix_len = len(v1_suffix) + 5 # 5 for ".json"
                if suffix_len == 5: # v1_suffix is empty
                    prefix_v1 = filename[:-5]
                else:
                    prefix_v1 = filename[:-suffix_len]
                configs_v1[prefix_v1] = val
                match_v1 = True
                
            # Match V2
            if filename.endswith(v2_suffix + ".json"):
                suffix_len = len(v2_suffix) + 5
                if suffix_len == 5: # v2_suffix is empty
                     prefix_v2 = filename[:-5]
                else:
                     prefix_v2 = filename[:-suffix_len]
                configs_v2[prefix_v2] = val

        # Find common prefixes and config-wise differences
        common_prefixes = set(configs_v1.keys()) & set(configs_v2.keys())
        differences = []
        excluded_configs = []
        
        for prefix in common_prefixes:
            val_v1 = configs_v1[prefix]
            val_v2 = configs_v2[prefix]
            
            # Check for outliers exclusion
            if exclude_threshold is not None:
                if val_v1 > exclude_threshold or val_v2 > exclude_threshold:
                    excluded_configs.append(prefix)
                    continue
            
            diff = val_v2 - val_v1
            differences.append(diff)
            
        if excluded_configs:
            print(f"Excluded {len(excluded_configs)} configs due to outlier threshold (> {exclude_threshold} ms):")
            for p in sorted(excluded_configs):
                print(f"  - {p}")
            print("-" * 50)
            
        if not differences:
            print("No matching config pairs found for the given versions (after exclusion).")
            sys.exit(0)
            
        # Calculate statistics
        count = len(differences)
        mean_val = np.mean(differences)
        std_val = np.std(differences, ddof=1) if count > 1 else 0.0
        min_val = np.min(differences)
        p25 = np.percentile(differences, 25)
        p50 = np.median(differences)
        p75 = np.percentile(differences, 75)
        max_val = np.max(differences)
        
        # Print results
        print(f"Statistics for P99 Latency Differences (V2 - V1)")
        print(f"V1 Suffix: '{v1_suffix}'")
        print(f"V2 Suffix: '{v2_suffix}'")
        print(f"--------------------------------------------------")
        print(f"count: {count}")
        print(f"mean:  {mean_val:.2f}")
        print(f"std:   {std_val:.2f}")
        print(f"min:   {min_val:.2f}")
        print(f"25%:   {p25:.2f}")
        print(f"50%:   {p50:.2f}")
        print(f"75%:   {p75:.2f}")
        print(f"max:   {max_val:.2f}")
        sys.exit(0)

    # Iterate based on mode
    data_points = []
    all_nodes = set()

    if aggregate_folders:
        # Mode 2: Aggregate from folders
        for dirname in os.listdir(results_dir):
            dirpath = os.path.join(results_dir, dirname)
            if not os.path.isdir(dirpath) or not re.match(r"results-.*config", dirname):
                continue

            # Filter by run if specified
            if target_run is not None:
                run_num = parse_run_number(dirname)
                if run_num != target_run:
                    continue
            
            # Aggregate latencies from all json files in this folder
            folder_p99_latencies = []
            folder_node_counts = {}
            folder_total_pods = 0
            
            # We need to find at least one valid file to get placements
            found_placements = False
            
            # Iterate all json files in the config folder
            for filename in os.listdir(dirpath):
                if not filename.endswith(".json"):
                    continue
                
                filepath = os.path.join(dirpath, filename)
                try:
                    with open(filepath, 'r') as f:
                        data = json.load(f)
                    
                    # Extract placements (only once per folder)
                    if not found_placements:
                        placements = data.get("placements", {})
                        for node, pods in placements.items():
                            count = len(pods)
                            folder_node_counts[node] = count
                            folder_total_pods += count
                            all_nodes.add(node)
                        found_placements = True
                    
                    # Extract latencies
                    lats = get_latencies(data)
                    folder_p99_latencies.extend(lats)

                except Exception as e:
                    print(f"Skipping file {dirname}/{filename}: {e}")
            if not folder_p99_latencies:
                print(f"Warning: No valid p99 data found in folder {dirname}")
                continue
            
            # Calculate average P99 latency
            avg_p99_latency = sum(folder_p99_latencies) / len(folder_p99_latencies)
            
            # Placement ID: use folder name as ID
            placement_id = re.sub(r"results-.*config", "P", dirname).replace("-", "")
            if target_config and placement_id == target_config:
                print(f"Config {placement_id}: Average P99 Latency = {avg_p99_latency:.2f} ms")
            
            # Add data point
            data_points.append({
                "id": placement_id,
                "latency": avg_p99_latency,
                "node_counts": folder_node_counts,
                "total_pods": folder_total_pods
            })
    else:
        # Mode 1: Flat files (Default)
        for filename in os.listdir(results_dir):
            if filename.endswith(".json"):
                # Filter by run if specified
                if target_run is not None:
                    run_num = parse_run_number(filename)
                    if run_num != target_run:
                        continue
                
                filepath = os.path.join(results_dir, filename)
                try:
                    with open(filepath, 'r') as f:
                        data = json.load(f)
                    
                    # Extract placements and count microservices per node
                    placements = data.get("placements", {})
                    node_counts = {}
                    total_pods = 0
                    for node, pods in placements.items():
                        count = len(pods)
                        node_counts[node] = count
                        total_pods += count
                        all_nodes.add(node)
                    
                    # Extract average P99 latency (ms) for mixed-workload
                    p99_latencies = get_latencies(data)
                    if not p99_latencies:
                        # Warning commented out to avoid spam if files are mixed
                        # print(f"Warning: No valid p99 data in {filename}")
                        continue
                    avg_p99_latency = sum(p99_latencies) / len(p99_latencies)
                    
                    # Placement ID from filename:
                    #   if rand search: rand-search-000.json -> P000
                    #   if bayes search: bayes-result-000.json -> P000
                    #   if results config: results-config<N>/run<M>.json -> P<N>-<M>
                    #   if results config file: results-config<N>.json -> P<N>
                    placement_id = "P"
                    if "rand-search" in filename:
                        placement_id += filename.replace("rand-search-", "")
                    elif "bayes-result" in filename:
                        placement_id += filename.replace("bayes-result-", "")
                    elif "run" in filename and "results-config-" in results_dir:
                        placement_id += results_dir[-1] + "-" + filename[3:]
                    elif filename.startswith("results-config-"):
                        placement_id += filename.replace("results-config-", "")
                    else:
                        print(f"Skipping {filename}: Unknown filename format.")
                        continue
                    placement_id = placement_id.replace(".json", "")

                    # Print latency for target config
                    if target_config and placement_id == target_config:
                        print(f"Config {placement_id}: Average P99 Latency = {avg_p99_latency:.2f} ms")

                    # Add data point to list 
                    data_points.append({
                        "id": placement_id,
                        "latency": avg_p99_latency,
                        "node_counts": node_counts,
                        "total_pods": total_pods
                    })
                except Exception as e:
                    print(f"Skipping {filename}: {e}")

    # Sort by latency and verify data points
    data_points.sort(key=lambda x: x["latency"])
    
    # Filter outliers and use valid points for plotting
    valid_points = []
    outliers = []
    for dp in data_points:
        if dp["latency"] > OUTLIER_THRESHOLD_MS:
            outliers.append(dp)
        else:
            valid_points.append(dp)
    
    # Check if we have any valid points
    if not valid_points and not outliers:
         print("No data found.")
         sys.exit(0)
    
    # If no valid points but we have outliers, just plot everything or warn
    if not valid_points:
        print(f"All data points exceeded the threshold ({OUTLIER_THRESHOLD_MS}ms). Plotting all...")
        valid_points = outliers
        outliers = []
        
    data_points = valid_points

    # Prepare for plotting
    ids = [d["id"] for d in data_points]
    latencies = [d["latency"] for d in data_points]
    unique_nodes = sorted(list(all_nodes))
    
    # Use a qualitative colormap
    colors_map = plt.get_cmap('tab10') 
    node_to_color = {node: colors_map(i % 10) for i, node in enumerate(unique_nodes)}

    # Set figure size
    plt.figure(figsize=(12, 6))
    bottoms = np.zeros(len(data_points))
    
    # Plot each node's contribution
    for node in unique_nodes:
        segment_heights = []
        for d in data_points:
             # Scale the height of the bar segment by the node's share of pods
             # The total height of the bar will be the latency
            if d["total_pods"] > 0:
                fraction = d["node_counts"].get(node, 0) / d["total_pods"]
                height = d["latency"] * fraction
            else:
                height = 0
            segment_heights.append(height)
        plt.bar(ids, segment_heights, bottom=bottoms, color=node_to_color[node], label=node)
        bottoms += np.array(segment_heights)
    
    # Add labels and title
    plt.xlabel('Placement Configuration')
    plt.ylabel('Avg P99 Latency (ms)')
    plt.title('P99 Latency for Mixed Workload by Placement')
    plt.xticks(rotation=45)
    plt.legend(title="Node Distribution", bbox_to_anchor=(1.05, 1), loc='upper left')
    
    # Add outlier text
    if outliers:
        outlier_text = f"Outliers (> {OUTLIER_THRESHOLD_MS}ms):\n"
        for dp in outliers[:5]:
            outlier_text += f"{dp['id']}: {dp['latency']:.2f} ms\n"
        if len(outliers) > 5:
             outlier_text += f"... + {len(outliers)-5} more"
        plt.text(1.05, 0.5, outlier_text, transform=plt.gca().transAxes, 
                 verticalalignment='top', fontsize=9, 
                 bbox=dict(boxstyle="round,pad=0.3", facecolor='white', alpha=0.9, edgecolor='gray'))
    plt.tight_layout()
    
    # Determine output filename
    # Format: {dir_name}-{mode_suffix}[-run{N}].png
    # Mode suffix: flat-dist (Mode 1) or agg-dist (Mode 2)
    
    dir_name = os.path.basename(results_dir.rstrip('/'))
    mode_suffix = "agg-dist" if aggregate_folders else "flat-dist"
    
    filename_parts = [dir_name, mode_suffix]
    
    if target_run is not None:
        filename_parts.append(f"run{target_run}")
        
    output_filename = "-".join(filename_parts) + ".png"
    output_image = os.path.join(results_dir, output_filename)
    
    plt.savefig(output_image, bbox_inches='tight')
    print(f"Graph saved to {output_image}")